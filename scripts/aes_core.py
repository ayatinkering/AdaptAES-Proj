RCON = [
    0x00,
    0x01,
    0x02,
    0x04,
    0x08,
    0x10,
    0x20,
    0x40,
    0x80,
    0x1B,
    0x36
]


def sub_bytes(state):
    return [S_BOX[b] for b in state]


def shift_rows(state):
    result = [0] * 16

    # AES state is stored column-major.
    result[0] = state[0]
    result[4] = state[4]
    result[8] = state[8]
    result[12] = state[12]

    result[1] = state[5]
    result[5] = state[9]
    result[9] = state[13]
    result[13] = state[1]

    result[2] = state[10]
    result[6] = state[14]
    result[10] = state[2]
    result[14] = state[6]

    result[3] = state[15]
    result[7] = state[3]
    result[11] = state[7]
    result[15] = state[11]

    return result


def xtime(a):
    a <<= 1

    if a & 0x100:
        a ^= 0x11B

    return a & 0xFF


def mix_single_column(a):
    t = a[0] ^ a[1] ^ a[2] ^ a[3]

    u = a[0]

    a[0] ^= t ^ xtime(a[0] ^ a[1])
    a[1] ^= t ^ xtime(a[1] ^ a[2])
    a[2] ^= t ^ xtime(a[2] ^ a[3])
    a[3] ^= t ^ xtime(a[3] ^ u)

    return a


def mix_columns(state):
    result = state[:]

    for col in range(4):
        start = col * 4

        column = [
            result[start],
            result[start + 1],
            result[start + 2],
            result[start + 3]
        ]

        column = mix_single_column(column)

        result[start] = column[0]
        result[start + 1] = column[1]
        result[start + 2] = column[2]
        result[start + 3] = column[3]

    return result


def add_round_key(state, round_key):
    return [
        state[i] ^ round_key[i]
        for i in range(16)
    ]


def rot_word(word):
    return word[1:] + word[:1]


def sub_word(word):
    return [S_BOX[b] for b in word]


def expand_key(key):
    if len(key) != 16:
        raise ValueError("AES-128 key must be exactly 16 bytes.")

    # AES-128 has 44 words.
    words = []

    for i in range(4):
        words.append(list(key[i * 4:(i + 1) * 4]))

    for i in range(4, 44):

        temp = words[i - 1][:]

        if i % 4 == 0:
            temp = rot_word(temp)
            temp = sub_word(temp)
            temp[0] ^= RCON[i // 4]

        new_word = [
            words[i - 4][j] ^ temp[j]
            for j in range(4)
        ]

        words.append(new_word)

    # Convert words into 11 round keys.
    round_keys = []

    for r in range(11):

        round_key = []

        for word in words[r * 4:(r + 1) * 4]:
            round_key.extend(word)

        round_keys.append(round_key)

    return round_keys


def encrypt_block(block, key, rounds=10):
    """
    Encrypt exactly one 16-byte block.

    rounds=10 -> standard AES-128
    rounds<10 -> experimental reduced-round AES
    """

    if len(block) != 16:
        raise ValueError("AES block must be exactly 16 bytes.")

    if len(key) != 16:
        raise ValueError("AES-128 key must be exactly 16 bytes.")

    if rounds < 1 or rounds > 10:
        raise ValueError("Rounds must be between 1 and 10.")

    round_keys = expand_key(key)

    state = list(block)

    # Initial AddRoundKey
    state = add_round_key(
        state,
        round_keys[0]
    )

    # Normal rounds
    for r in range(1, rounds):

        state = sub_bytes(state)

        state = shift_rows(state)

        state = mix_columns(state)

        state = add_round_key(
            state,
            round_keys[r]
        )

    # Final round
    # AES final round does NOT contain MixColumns.
    state = sub_bytes(state)

    state = shift_rows(state)

    state = add_round_key(
        state,
        round_keys[rounds]
    )

    return bytes(state)