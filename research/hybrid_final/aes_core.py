# -----------------------------
# AES BASIC OPERATIONS
# -----------------------------

def sub_bytes(state):
    return [S_BOX[x] for x in state]


def inv_sub_bytes(state):
    return [INV_S_BOX[x] for x in state]


def shift_rows(state):
    result = [0] * 16

    for r in range(4):
        for c in range(4):
            result[4 * c + r] = state[4 * ((c + r) % 4) + r]

    return result


def inv_shift_rows(state):
    result = [0] * 16

    for r in range(4):
        for c in range(4):
            result[4 * c + r] = state[4 * ((c - r) % 4) + r]

    return result


def xtime(a):
    return ((a << 1) ^ 0x1B) & 0xFF if a & 0x80 else (a << 1)


def gmul(a, b):
    result = 0

    for _ in range(8):
        if b & 1:
            result ^= a

        high_bit = a & 0x80
        a = (a << 1) & 0xFF

        if high_bit:
            a ^= 0x1B

        b >>= 1

    return result


def mix_single_column(column):
    a = column[:]

    column[0] = (
        gmul(a[0], 2) ^
        gmul(a[1], 3) ^
        a[2] ^
        a[3]
    )

    column[1] = (
        a[0] ^
        gmul(a[1], 2) ^
        gmul(a[2], 3) ^
        a[3]
    )

    column[2] = (
        a[0] ^
        a[1] ^
        gmul(a[2], 2) ^
        gmul(a[3], 3)
    )

    column[3] = (
        gmul(a[0], 3) ^
        a[1] ^
        a[2] ^
        gmul(a[3], 2)
    )

    return column


def mix_columns(state):
    result = state[:]

    for c in range(4):
        column = [
            state[4 * c],
            state[4 * c + 1],
            state[4 * c + 2],
            state[4 * c + 3]
        ]

        mixed = mix_single_column(column)

        for r in range(4):
            result[4 * c + r] = mixed[r]

    return result


def inv_mix_columns(state):
    result = state[:]

    for c in range(4):
        a0 = state[4 * c]
        a1 = state[4 * c + 1]
        a2 = state[4 * c + 2]
        a3 = state[4 * c + 3]

        result[4 * c] = (
            gmul(a0, 14) ^
            gmul(a1, 11) ^
            gmul(a2, 13) ^
            gmul(a3, 9)
        )

        result[4 * c + 1] = (
            gmul(a0, 9) ^
            gmul(a1, 14) ^
            gmul(a2, 11) ^
            gmul(a3, 13)
        )

        result[4 * c + 2] = (
            gmul(a0, 13) ^
            gmul(a1, 9) ^
            gmul(a2, 14) ^
            gmul(a3, 11)
        )

        result[4 * c + 3] = (
            gmul(a0, 11) ^
            gmul(a1, 13) ^
            gmul(a2, 9) ^
            gmul(a3, 14)
        )

    return result


def add_round_key(state, round_key):
    return [state[i] ^ round_key[i] for i in range(16)]


# -----------------------------
# KEY EXPANSION
# -----------------------------

def rot_word(word):
    return word[1:] + word[:1]


def sub_word(word):
    return [S_BOX[x] for x in word]


def expand_key(key):
    if len(key) != 16:
        raise ValueError("AES-128 key must be exactly 16 bytes.")

    words = []

    for i in range(4):
        words.append(list(key[4 * i:4 * i + 4]))

    for i in range(4, 44):
        temp = words[i - 1][:]

        if i % 4 == 0:
            temp = rot_word(temp)
            temp = sub_word(temp)
            temp[0] ^= RCON[i // 4]

        new_word = [
            words[i - 4][j] ^ temp[j]
            for j in range(4)
        ]

        words.append(new_word)

    round_keys = []

    for r in range(11):
        round_key = []

        for word in words[4 * r:4 * r + 4]:
            round_key.extend(word)

        round_keys.append(round_key)

    return round_keys


# -----------------------------
# BLOCK ENCRYPTION
# -----------------------------

def encrypt_block(block, key, rounds=10):
    if len(block) != 16:
        raise ValueError("AES block must be exactly 16 bytes.")

    if len(key) != 16:
        raise ValueError("AES-128 key must be exactly 16 bytes.")

    if rounds < 1 or rounds > 10:
        raise ValueError("Rounds must be between 1 and 10.")

    round_keys = expand_key(key)

    state = list(block)

    # Initial AddRoundKey
    state = add_round_key(state, round_keys[0])

    # Full rounds
    for r in range(1, rounds):
        state = sub_bytes(state)
        state = shift_rows(state)
        state = mix_columns(state)
        state = add_round_key(state, round_keys[r])

    # Final round
    state = sub_bytes(state)
    state = shift_rows(state)
    state = add_round_key(state, round_keys[rounds])

    return bytes(state)


# -----------------------------
# BLOCK DECRYPTION
# -----------------------------

def decrypt_block(block, key, rounds=10):
    if len(block) != 16:
        raise ValueError("AES block must be exactly 16 bytes.")

    if len(key) != 16:
        raise ValueError("AES-128 key must be exactly 16 bytes.")

    if rounds < 1 or rounds > 10:
        raise ValueError("Rounds must be between 1 and 10.")

    round_keys = expand_key(key)

    state = list(block)

    # Undo final round
    state = add_round_key(state, round_keys[rounds])
    state = inv_shift_rows(state)
    state = inv_sub_bytes(state)

    # Undo intermediate rounds
    for r in range(rounds - 1, 0, -1):
        state = add_round_key(state, round_keys[r])
        state = inv_mix_columns(state)
        state = inv_shift_rows(state)
        state = inv_sub_bytes(state)

    # Undo initial AddRoundKey
    state = add_round_key(state, round_keys[0])

    return bytes(state)


# -----------------------------
# PKCS#7 PADDING
# -----------------------------

def pad_data(data):
    padding_length = 16 - (len(data) % 16)

    padding = bytes([padding_length]) * padding_length

    return data + padding


def unpad_data(data):
    if len(data) == 0:
        raise ValueError("Cannot unpad empty data.")

    padding_length = data[-1]

    if padding_length < 1 or padding_length > 16:
        raise ValueError("Invalid padding.")

    if data[-padding_length:] != bytes([padding_length]) * padding_length:
        raise ValueError("Invalid padding.")

    return data[:-padding_length]


# -----------------------------
# ARBITRARY-LENGTH DATA
# -----------------------------

def encrypt_data(data, key):
    padded_data = pad_data(data)

    ciphertext = bytearray()

    for i in range(0, len(padded_data), 16):
        block = padded_data[i:i + 16]

        encrypted_block = encrypt_block(
            block,
            key,
            rounds=10
        )

        ciphertext.extend(encrypted_block)

    return bytes(ciphertext)


def decrypt_data(ciphertext, key):
    if len(ciphertext) % 16 != 0:
        raise ValueError("Ciphertext length must be a multiple of 16.")

    plaintext = bytearray()

    for i in range(0, len(ciphertext), 16):
        block = ciphertext[i:i + 16]

        decrypted_block = decrypt_block(
            block,
            key,
            rounds=10
        )

        plaintext.extend(decrypted_block)

    return unpad_data(bytes(plaintext))

